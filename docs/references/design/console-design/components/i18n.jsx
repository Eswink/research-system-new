/* i18n — lightweight, dependency-free translation layer.
   Design decisions:
   - Two locales: en (default) + zh-CN
   - Technical mono terms (state enums like VERIFIED / PROPOSED, model IDs,
     digests, provider names) STAY IN ENGLISH intentionally — they are
     product vocabulary, not prose. Translating them hurts the tool's
     scientific-precision feel.
   - Only UI chrome (nav, breadcrumbs, actions, hints, headlines) is
     translated. Screens that are dense technical readouts remain English
     under both locales.
   - Language choice is persisted in localStorage under `ros.lang`.
   - <html lang> is kept in sync so screen readers announce correctly.
*/

